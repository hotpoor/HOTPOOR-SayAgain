const {_electron:electron}=require('playwright'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {Service}=require('../desktop/service.cjs'),{persist}=require('../desktop/speaker-pipeline.cjs');
const root=path.resolve(__dirname,'..'),directory=fs.mkdtempSync(path.join(os.tmpdir(),'sayagain-nvidia-ui-'));
const output=path.join(root,'test-results');fs.mkdirSync(output,{recursive:true});
const bytes=Buffer.alloc(32044);bytes.write('RIFF');bytes.writeUInt32LE(bytes.length-8,4);bytes.write('WAVEfmt ',8);bytes.writeUInt32LE(16,16);bytes.writeUInt16LE(1,20);bytes.writeUInt16LE(1,22);bytes.writeUInt32LE(16000,24);bytes.writeUInt32LE(32000,28);bytes.writeUInt16LE(2,32);bytes.writeUInt16LE(16,34);bytes.write('data',36);bytes.writeUInt32LE(32000,40);
fs.writeFileSync(path.join(directory,'00001.wav'),bytes);
const service=new Service(path.join(directory,'data'));
const sources=[{audio:path.join(directory,'00001.wav'),name:'模式对比样例.wav',offset_ms:0,duration_ms:1000}];
const clip={file:'00001.wav',source_index:0,start_ms:0,end_ms:1000,speaker:'A',similarity:.8,review:false,text:'这是原有模式的文字，保留不变。'};
const manifest={version:'speaker-clips-v1',engine:'campplus',options:{language:'zh'},elapsed_seconds:5,clips:[clip]};
const session=persist(service,directory,manifest,sources,'NVIDIA 分人模式对比');
const firstSource=service.store.list('recording_source')[0];
persist(service,directory,{...manifest,engine:'nemotron',device:'cuda',elapsed_seconds:3.5,peak_cuda_bytes:512*1024*1024,comparison_source_id:firstSource.block_id,clips:[{...clip,speaker:null,speakers:['A','B'],review:true,text:'这是重叠发言，需要核对。'}]},sources,'Comparison',session);
service.close();let app;
(async()=>{try{
 app=await electron.launch({args:[root],env:{...process.env,SAYAGAIN_DATA_DIR:directory},timeout:60000});
 const page=await app.firstWindow(),errors=[];page.on('pageerror',e=>{errors.push(e.message);console.error('PAGE',e.message);});await page.waitForSelector('#main .page');
 await page.locator('#language-form button[type="submit"]').click();await page.waitForSelector('[data-action="example"]');await page.locator('[data-page="recordings"]').click();
 await page.locator('[data-pipeline-engine="nemotron"]').click();
 assert.equal(await page.locator('#pipeline-count').isDisabled(),true);
 assert(await page.locator('[data-pipeline-engine="nemotron"] img').evaluate(el=>el.complete&&el.naturalWidth>0));
 await page.locator('[data-recording-open]').first().click();
 assert.equal(await page.locator('.conversation-source').count(),2);
 assert((await page.locator('.pipeline-badge').allTextContents()).some(t=>t.includes('NVIDIA Nemotron 3')&&t.includes('3.5 秒')));
 assert.equal(await page.locator('[data-pipeline-compare]').count(),2);
 await page.locator('.recordings-tools > summary').click();
 await page.screenshot({path:path.join(output,'nemotron-comparison.png'),fullPage:true});
 await page.locator('[data-compare-engine="nemotron"]').click();
 await page.waitForFunction(()=>document.querySelector('#recording-status').textContent.includes('尚未安装'));
 assert.equal(await page.locator('.conversation-source').count(),2);
 assert.deepEqual(errors,[]);
 console.log('PASS: mode choice, official logo, preserved comparisons, overlap display and missing-model error');
}finally{await app?.close();}})().catch(e=>{console.error(e);process.exitCode=1;});
